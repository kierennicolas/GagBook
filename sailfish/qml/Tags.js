// Returns up to 'limit' tags whose name starts with or contains 'text', best matches first.
// Sensitive tags are only included if 'includeSensitive' is true.
function suggestions(text, includeSensitive, limit) {
    var query = text.trim().toLowerCase()
    var starts = [], contains = []
    for (var i = 0; i < tags.length; ++i) {
        var t = tags[i]
        if (t[2] && !includeSensitive)
            continue
        var pos = query.length ? t[0].indexOf(query) : 0
        if (pos === 0)
            starts.push(t)
        else if (pos > 0)
            contains.push(t)
    }
    return starts.concat(contains).slice(0, limit)
}

// Turns typed text into a tag url slug the way 9GAG does: 'old meme' -> 'old-meme'
function slugFor(text) {
    var query = text.trim().toLowerCase()
    for (var i = 0; i < tags.length; ++i) {
        if (tags[i][0] === query)
            return tags[i][1]
    }
    return query.replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '')
}
